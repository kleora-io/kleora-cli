/**
 * `kleora completion <shell>` — bash, zsh, fish.
 *
 * It completes nouns, verbs and flags from static metadata and **never by
 * calling the API**: a completion that makes an HTTP request spends a rate
 * limit budget on a keystroke and hangs a person's shell when the network is
 * slow.
 *
 * So everything below is generated from the registry and the generated
 * operations at *print* time, in this process, with no credential and no
 * network. The script the person installs is then pure shell: it has no way to
 * make a request, which is a stronger guarantee than a promise not to.
 * `test/completion.test.ts` asserts the `fetch` it is given is never called.
 */
import { usageFailure } from '../exit.js'
import type { Io } from '../output.js'
import { COMMANDS, nouns, verbsFor } from './registry.js'
import { allowedFlags, GLOBAL_FLAGS, TOOL_COMMANDS } from './surface.js'

export function completion(shell: string | undefined, io: Io): void {
  switch (shell) {
    case 'bash':
      io.out(bash())
      return
    case 'zsh':
      io.out(zsh())
      return
    case 'fish':
      io.out(fish())
      return
    default:
      throw usageFailure(
        `\`kleora completion\` needs a shell: bash, zsh or fish.`,
        '',
        '  bash:  kleora completion bash >> ~/.bashrc',
        '  zsh:   kleora completion zsh  >> ~/.zshrc',
        '  fish:  kleora completion fish > ~/.config/fish/completions/kleora.fish',
      )
  }
}

/** Every flag a given `noun verb` accepts, as a sorted `--x` list. */
function flagsFor(noun: string, verb: string): string[] {
  const command = COMMANDS.find((entry) => entry.noun === noun && entry.verb === verb)
  if (command === undefined) return [...GLOBAL_FLAGS].map((flag) => `--${flag}`).sort()
  return [...allowedFlags(command)].map((flag) => `--${flag}`).sort()
}

const ALL_NOUNS = (): string => [...nouns(), ...TOOL_COMMANDS].join(' ')

function bash(): string {
  const cases = nouns()
    .map((noun) => `      ${noun}) verbs="${verbsFor(noun).map((v) => v.verb).join(' ')}" ;;`)
    .join('\n')
  const flagCases = COMMANDS.map(
    (command) =>
      `      "${command.noun} ${command.verb}") flags="${flagsFor(command.noun, command.verb).join(' ')}" ;;`,
  ).join('\n')

  return `# kleora completion for bash. Generated by \`kleora completion bash\`.
# It makes no network request: every name below is baked in at generation time.
_kleora_completion() {
  local cur prev nouns verbs flags
  cur="\${COMP_WORDS[COMP_CWORD]}"
  nouns="${ALL_NOUNS()}"

  if [ "$COMP_CWORD" -eq 1 ]; then
    COMPREPLY=( $(compgen -W "$nouns" -- "$cur") )
    return
  fi

  case "\${COMP_WORDS[1]}" in
${cases}
      completion) verbs="bash zsh fish" ;;
      *) verbs="" ;;
  esac

  if [ "$COMP_CWORD" -eq 2 ]; then
    COMPREPLY=( $(compgen -W "$verbs" -- "$cur") )
    return
  fi

  case "\${COMP_WORDS[1]} \${COMP_WORDS[2]}" in
${flagCases}
      *) flags="${[...GLOBAL_FLAGS].map((flag) => `--${flag}`).join(' ')}" ;;
  esac
  COMPREPLY=( $(compgen -W "$flags" -- "$cur") )
}
complete -F _kleora_completion kleora kleora-auth
`
}

function zsh(): string {
  const nounDescriptions = nouns()
    .map((noun) => `    '${noun}:${verbsFor(noun).length} command(s)'`)
    .join('\n')
  const verbCases = nouns()
    .map(
      (noun) =>
        `      ${noun}) _values verb ${verbsFor(noun)
          .map((command) => `'${command.verb}'`)
          .join(' ')} ;;`,
    )
    .join('\n')
  const flagCases = COMMANDS.map(
    (command) =>
      `        "${command.noun}:${command.verb}") _values flag ${flagsFor(command.noun, command.verb)
        .map((flag) => `'${flag}'`)
        .join(' ')} ;;`,
  ).join('\n')

  return `#compdef kleora kleora-auth
# kleora completion for zsh. Generated by \`kleora completion zsh\`.
# It makes no network request: every name below is baked in at generation time.
_kleora() {
  if (( CURRENT == 2 )); then
    _values 'command' \\
${nounDescriptions} \\
${TOOL_COMMANDS.map((name) => `    '${name}'`).join(' \\\n')}
    return
  fi
  if (( CURRENT == 3 )); then
    case "\${words[2]}" in
${verbCases}
      completion) _values shell 'bash' 'zsh' 'fish' ;;
    esac
    return
  fi
  case "\${words[2]}:\${words[3]}" in
${flagCases}
        *) _values flag ${[...GLOBAL_FLAGS].map((flag) => `'--${flag}'`).join(' ')} ;;
  esac
}
_kleora "$@"
`
}

function fish(): string {
  const lines: string[] = [
    '# kleora completion for fish. Generated by `kleora completion fish`.',
    '# It makes no network request: every name below is baked in at generation time.',
    'complete -c kleora -f',
  ]
  for (const noun of [...nouns(), ...TOOL_COMMANDS]) {
    lines.push(`complete -c kleora -n "__fish_use_subcommand" -a "${noun}"`)
  }
  for (const command of COMMANDS) {
    lines.push(
      `complete -c kleora -n "__fish_seen_subcommand_from ${command.noun}" -a "${command.verb}" -d "${command.summary.replace(/"/g, "'")}"`,
    )
    for (const flag of flagsFor(command.noun, command.verb)) {
      lines.push(
        `complete -c kleora -n "__fish_seen_subcommand_from ${command.noun}" -l "${flag.slice(2)}"`,
      )
    }
  }
  for (const shell of ['bash', 'zsh', 'fish']) {
    lines.push(`complete -c kleora -n "__fish_seen_subcommand_from completion" -a "${shell}"`)
  }
  return `${lines.join('\n')}\n`
}
